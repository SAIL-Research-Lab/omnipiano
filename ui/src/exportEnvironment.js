import { strToU8, zipSync } from "fflate";

export const ENVIRONMENT_BUNDLE_SCHEMA_VERSION = 1;

function slugify(value, fallback = "task") {
  const normalized = String(value ?? "")
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 64);
  const slug = normalized || fallback;
  return /^[a-z_]/.test(slug) ? slug : `task_${slug}`;
}

function jsonText(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function fingerprint(value) {
  const source = JSON.stringify(value);
  let hash = 0x811c9dc5;
  for (let index = 0; index < source.length; index += 1) {
    hash ^= source.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return `fnv1a-${(hash >>> 0).toString(16).padStart(8, "0")}`;
}

function marlTask(config, taskName) {
  const design = config.design.config;
  const assignment = design.assignment === "territorial" ? "default" : design.assignment;
  return {
    name: taskName.replaceAll("_", "-"),
    song: config.task.music.piece,
    num_hands: config.task.embodiment.num_hands,
    num_agents: design.num_agents,
    assignment,
    sustain_owner: design.sustain_owner,
    agents: design.agents.map((agent) => ({
      name: agent.name,
      hand_ids: [...agent.hand_ids],
      action_key_range: [...agent.action_key_range],
      observation_key_range: [...agent.observation_key_range],
      visible_teammate_hands: Array.isArray(agent.visible_teammate_hands)
        ? [...agent.visible_teammate_hands]
        : agent.visible_teammate_hands,
    })),
  };
}

export function buildEnvironmentSpec(config) {
  const track = config.design.type;
  const taskName = slugify(config.experiment.name);
  if (track === "marl") {
    if (config.task.source !== "custom") {
      throw new Error("Multi-Agent RL export requires a custom task.");
    }
    return {
      schema_version: ENVIRONMENT_BUNDLE_SCHEMA_VERSION,
      format: "omnipiano.environment",
      name: taskName,
      track,
      api: "pettingzoo_parallel",
      task: {
        source: "custom",
        spec: marlTask(config, taskName),
      },
      runtime: {
        inter_agent_collision_penalty_coef:
          config.design.config.coordination?.inter_agent_collision_penalty_coefficient ?? 0,
      },
    };
  }
  if (!config.task.environment_id) {
    throw new Error("Choose a registered environment before exporting.");
  }
  return {
    schema_version: ENVIRONMENT_BUNDLE_SCHEMA_VERSION,
    format: "omnipiano.environment",
    name: taskName,
    track,
    api: "gymnasium",
    task: {
      source: "registered",
      environment_id: config.task.environment_id,
    },
  };
}

function registeredInitializer(track) {
  const safetyRegistration = track === "safety"
    ? "    from omnipiano.safety.suite import register_all\n\n    register_all()\n"
    : "";
  return `"""Importable environment adapter generated by OmniPiano."""

import json
from pathlib import Path

import omnipiano


_TASK_FILE = Path(__file__).with_name("task.json")


def load_spec():
    """Return a detached copy of the exported environment specification."""
    return json.loads(_TASK_FILE.read_text(encoding="utf-8"))


def make_env(*, seed=None, mode="train", **kwargs):
    """Create the configured Gymnasium environment."""
${safetyRegistration}    specification = load_spec()
    if seed is not None:
        kwargs["seed"] = seed
    return omnipiano.make(
        specification["task"]["environment_id"],
        mode=mode,
        **kwargs,
    )


__all__ = ["load_spec", "make_env"]
`;
}

function marlInitializer() {
  return `"""Importable environment adapter generated by OmniPiano."""

import json
from pathlib import Path

from omnipiano.multiagent import make_parallel_from_task
from omnipiano.multiagent.compile import compile_task


_TASK_FILE = Path(__file__).with_name("task.json")


def load_spec():
    """Return a detached copy of the exported environment specification."""
    return json.loads(_TASK_FILE.read_text(encoding="utf-8"))


def make_env(*, seed=None, **kwargs):
    """Create the configured PettingZoo ParallelEnv."""
    specification = load_spec()
    task = compile_task(specification["task"]["spec"])
    for name, value in specification.get("runtime", {}).items():
        kwargs.setdefault(name, value)
    return make_parallel_from_task(task, seed=seed, **kwargs)


__all__ = ["load_spec", "make_env"]
`;
}

function quickstart(packageName, track) {
  if (track === "marl") {
    return `"""Smoke-test the exported PettingZoo environment with random actions."""

from ${packageName} import make_env


env = make_env(seed=0)
observations, infos = env.reset(seed=0)

while env.agents:
    actions = {agent: env.action_space(agent).sample() for agent in env.agents}
    observations, rewards, terminations, truncations, infos = env.step(actions)

env.close()
print("Environment smoke test completed.")
`;
  }
  return `"""Smoke-test the exported Gymnasium environment with random actions."""

from ${packageName} import make_env


env = make_env(seed=0)
observation, info = env.reset(seed=0)
terminated = truncated = False

while not (terminated or truncated):
    observation, reward, terminated, truncated, info = env.step(env.action_space.sample())

env.close()
print("Environment smoke test completed.")
`;
}

function readme(specification, packageName) {
  const apiLabel = specification.api === "pettingzoo_parallel"
    ? "PettingZoo ParallelEnv"
    : "Gymnasium Env";
  const modeNote = specification.track === "robust"
    ? "For robust evaluation, call `make_env(mode=\"eval\", eval_noise_scale=1.0)`."
    : "";
  return `# ${specification.name}

This bundle was exported by the OmniPiano Experiment Composer. It contains an
algorithm-independent environment specification and a thin import adapter. The
simulator remains provided by the installed \`omnipiano\` Python package.

## Install

From an OmniPiano source checkout:

\`\`\`bash
pip install -e /path/to/omnipiano
\`\`\`

When a packaged release is available:

\`\`\`bash
pip install omnipiano
\`\`\`

## Add to your workspace

Place the \`${packageName}\` directory at the root of your algorithm project,
then create the configured ${apiLabel}:

\`\`\`python
from ${packageName} import make_env

env = make_env(seed=0)
\`\`\`

Run the included smoke test from the parent directory:

\`\`\`bash
python -m ${packageName}.quickstart
\`\`\`

${modeNote}

The environment definition is in \`task.json\`; \`manifest.json\` records the
bundle format, API family, import path, and deterministic task fingerprint.
Algorithm parameters and training settings are intentionally not included.
`;
}

export function buildEnvironmentBundle(config) {
  const specification = buildEnvironmentSpec(config);
  const packageName = `omnipiano_env_${slugify(specification.name)}`;
  const manifest = {
    bundle_schema_version: ENVIRONMENT_BUNDLE_SCHEMA_VERSION,
    generator: "OmniPiano Experiment Composer",
    environment_name: specification.name,
    track: specification.track,
    api: specification.api,
    python_package: packageName,
    import_statement: `from ${packageName} import make_env`,
    task_fingerprint: fingerprint(specification),
  };
  const prefix = `${packageName}/`;
  const files = {
    [`${prefix}__init__.py`]: specification.track === "marl"
      ? marlInitializer()
      : registeredInitializer(specification.track),
    [`${prefix}task.json`]: jsonText(specification),
    [`${prefix}manifest.json`]: jsonText(manifest),
    [`${prefix}quickstart.py`]: quickstart(packageName, specification.track),
    [`${prefix}README.md`]: readme(specification, packageName),
    [`${prefix}requirements.txt`]: "# Install OmniPiano from PyPI or from its source checkout.\nomnipiano\n",
  };
  return {
    archiveName: `${packageName}.zip`,
    packageName,
    specification,
    manifest,
    files,
    importSnippet: `${manifest.import_statement}\n\nenv = make_env(seed=0)\n`,
  };
}

export function createEnvironmentArchive(config) {
  const bundle = buildEnvironmentBundle(config);
  const entries = Object.fromEntries(
    Object.entries(bundle.files).map(([path, content]) => [path, strToU8(content)]),
  );
  return {
    ...bundle,
    bytes: zipSync(entries, { level: 6 }),
  };
}

function triggerDownload(blob, filename) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 0);
}

export function downloadEnvironmentArchive(config) {
  const bundle = createEnvironmentArchive(config);
  triggerDownload(new Blob([bundle.bytes], { type: "application/zip" }), bundle.archiveName);
  return bundle;
}

export function downloadEnvironmentTask(config) {
  const bundle = buildEnvironmentBundle(config);
  triggerDownload(
    new Blob([jsonText(bundle.specification)], { type: "application/json" }),
    `${bundle.packageName}-task.json`,
  );
  return bundle;
}
